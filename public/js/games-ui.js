'use strict';
window.TVGames={async mount(el,onSelect){const games=await TV.api('/api/games');
const primary=games.filter(g=>g.displayGroup==='primary'),more=games.filter(g=>g.displayGroup==='more');
const current=TV.gameParam();
function b(g){const x=document.createElement('button');
x.textContent=g.name;
x.dataset.game=g.id;
x.classList.toggle('on',g.id===current);
x.onclick=()=>{TV.qsa('.game-tabs button').forEach(z=>z.classList.remove('on'));
x.classList.add('on');
TV.setGame(g.id);
TV.api('/api/activity',{method:'POST'}).catch(()=>{});
onSelect(g);
};
return x;
}primary.forEach(g=>el.append(b(g)));
if(more.length){const x=document.createElement('button');
x.textContent='＋ 더보기';
x.onclick=()=>{const modal=document.getElementById('moreGames');
const body=modal.querySelector('.more-body');
body.replaceChildren(...more.map(b));
modal.classList.add('on');
};
el.append(x);
}return games;
}};
