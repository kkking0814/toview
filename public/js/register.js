'use strict';
let verifiedEmail='';
const $=id=>document.getElementById(id);
$('sendCode').onclick=async()=>{try{const d=await TV.api('/api/email/send',{method:'POST',body:JSON.stringify({email:$('email').value})});
$('verifyState').textContent=d.devCode?`개발환경 인증번호: ${d.devCode}`:'인증번호를 발송했습니다.';
}catch(e){alert(e.message);
}};
$('verifyCode').onclick=async()=>{try{const d=await TV.api('/api/email/verify',{method:'POST',body:JSON.stringify({email:$('email').value,code:$('emailCode').value})});
verifiedEmail=d.email;
$('verifyState').textContent='이메일 인증 완료';
}catch(e){verifiedEmail='';
alert(e.message);
}};
$('email').addEventListener('input',()=>{if(verifiedEmail&&$('email').value.trim().toLowerCase()!==verifiedEmail){verifiedEmail='';
$('verifyState').textContent='이메일이 변경되어 다시 인증해야 합니다.';
}});
$('registerForm').onsubmit=async e=>{e.preventDefault();
if(!verifiedEmail)return alert('이메일 인증을 완료해 주세요.');
try{await TV.api('/api/register',{method:'POST',body:JSON.stringify({username:$('username').value,nickname:$('nickname').value,email:$('email').value,password:$('password').value})});
alert('가입되었습니다.');
location.href='account.html';
}catch(x){alert(x.message);
}};
